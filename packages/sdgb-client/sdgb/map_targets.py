def target_distance(map_id: int) -> int | None:
    """该区域的终点距离；未收录返回 None（调用方保持原 distance）。"""
    return MAP_TARGET_DISTANCE.get(int(map_id))


def map_id_by_name(name: str) -> int | None:
    """按区域名查 mapId：先精确匹配，唯一包含匹配也可；歧义返回 None。"""
    name = (name or "").strip()
    if not name:
        return None
    for map_id, mapped in MAP_NAMES.items():
        if mapped == name:
            return map_id
    hits = [m for m, mapped in MAP_NAMES.items() if name in mapped]
    return hits[0] if len(hits) == 1 else None
